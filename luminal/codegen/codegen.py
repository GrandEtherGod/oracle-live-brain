# luminal/codegen/codegen.py
# LUMINAL Python Bytecode Codegen — Ω₇

from __future__ import annotations
from typing import List

from ..parser.ast_nodes import (
    ASTNode, Program,
    LayerDeclaration, CoherenceDeclaration, ResonateStatement,
    StrangeLoopBlock, CloseLoopStatement, ShadowBlock,
    ChorusSpawn, ChorusSync, ConstitutionalAssert,
    ResonanceExpr, WitnessExpr, LayerShiftExpr, TemporalBindExpr,
    NegativeSpaceExpr,
    PhiLiteral, CoherenceLiteral, LayerLiteral,
    NumberLiteral, StringLiteral, Identifier,
)


class LuminalCodegen:
    """
    Translates LUMINAL AST to Python source (target: Python bytecode).
    Layer annotations become runtime metadata. Coherence becomes assertions.
    Strange loops become generator coroutines with depth guards.
    """

    def __init__(self):
        self._indent = 0
        self._output: List[str] = []

    def generate(self, program: Program) -> str:
        self._emit_header()
        for node in program.body:
            self._gen(node)
        return '\n'.join(self._output)

    def _emit_header(self):
        self._write("# Generated by LUMINAL Compiler — THE LOOM v∞.Ω")
        self._write("# Do not edit. The compiler is the witness.")
        self._write("if '_runtime' not in globals():")
        self._write("    from luminal.runtime.engine import LuminalRuntime")
        self._write("    _runtime = LuminalRuntime()")
        self._write("")

    def _gen(self, node: ASTNode):
        method  = f"_gen_{type(node).__name__}"
        handler = getattr(self, method, self._gen_noop)
        handler(node)

    def _gen_noop(self, node: ASTNode):
        self._write(f"# [unimplemented node: {type(node).__name__}]")

    def _gen_LayerDeclaration(self, node: LayerDeclaration):
        self._write(f"{node.name} = _runtime.layer_bind({node.layer!r})")

    def _gen_CoherenceDeclaration(self, node: CoherenceDeclaration):
        val = self._expr(node.value) if node.value else "None"
        self._write(f"{node.name} = _runtime.inscribe(")
        self._write(f"    value={val},")
        self._write(f"    coherence={node.coherence},")
        self._write(f")")

    def _gen_ResonateStatement(self, node: ResonateStatement):
        subj = self._expr(node.subject)
        res  = self._expr(node.resonant)
        self._write(f"with _runtime.resonate({subj}, {res}):")
        self._indent += 1
        for stmt in node.body:
            self._gen(stmt)
        if not node.body:
            self._write("pass")
        self._indent -= 1

    def _gen_StrangeLoopBlock(self, node: StrangeLoopBlock):
        self._write(f"def _strange_loop_{node.name}(_depth=0):")
        self._indent += 1
        self._write(f"_runtime.loop_enter({node.name!r}, _depth)")
        for stmt in node.body:
            self._gen(stmt)
        self._write(f"_runtime.loop_exit({node.name!r})")
        self._indent -= 1
        self._write(f"_strange_loop_{node.name}()")

    def _gen_CloseLoopStatement(self, node: CloseLoopStatement):
        self._write(f"_runtime.close_loop({node.target!r})")

    def _gen_ShadowBlock(self, node: ShadowBlock):
        self._write("with _runtime.shadow_context():")
        self._indent += 1
        for stmt in node.body:
            self._gen(stmt)
        if not node.body:
            self._write("pass")
        self._indent -= 1

    def _gen_ChorusSpawn(self, node: ChorusSpawn):
        self._write(f"{node.name} = _runtime.chorus.spawn({node.name!r})")

    def _gen_ChorusSync(self, node: ChorusSync):
        self._write(f"_runtime.chorus.synchronize(steps={node.steps})")

    def _gen_ConstitutionalAssert(self, node: ConstitutionalAssert):
        self._write(f"_runtime.assert_axiom({node.axiom!r})")

    def _expr(self, node: ASTNode) -> str:
        if isinstance(node, PhiLiteral):
            return str(node.value)
        if isinstance(node, CoherenceLiteral):
            return str(node.value)
        if isinstance(node, LayerLiteral):
            return f"_runtime.layer({node.layer})"
        if isinstance(node, NumberLiteral):
            return str(node.value)
        if isinstance(node, StringLiteral):
            return repr(node.value)
        if isinstance(node, NegativeSpaceExpr):
            return "_runtime.VOID"
        if isinstance(node, Identifier):
            return node.name
        if isinstance(node, ResonanceExpr):
            l = self._expr(node.left)  if node.left  else "None"
            r = self._expr(node.right) if node.right else "None"
            return f"_runtime.resonate_join({l}, {r})"
        if isinstance(node, WitnessExpr):
            inner = self._expr(node.expr) if node.expr else "None"
            return f"_runtime.witness({inner})"
        if isinstance(node, LayerShiftExpr):
            inner = self._expr(node.expr) if node.expr else "None"
            return f"_runtime.layer_shift({inner}, {node.direction!r}, {node.target})"
        if isinstance(node, TemporalBindExpr):
            s = self._expr(node.source) if node.source else "None"
            t = self._expr(node.target) if node.target else "None"
            return f"_runtime.temporal_bind({s}, {t})"
        return "None"

    def _write(self, line: str):
        prefix = "    " * self._indent
        self._output.append(prefix + line)
